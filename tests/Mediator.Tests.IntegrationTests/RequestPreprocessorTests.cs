namespace Boutquin.Mediator.Tests.IntegrationTests;

// Boutquin.Mediator
using Abstractions;
using Boutquin.Domain.Abstractions;
// Boutquin.Mediator.Tests
using Common;
using Extensions;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using Moq;
using Pipeline;

/// <summary>
/// Contains unit tests for verifying the behavior of the mediator pipeline, including the integration of preprocessors,
/// handlers, and logging functionality.
/// </summary>
/// <remarks>This class includes tests that validate the correct processing of commands and queries by the
/// mediator, ensuring that preprocessors and handlers function as expected. The tests also verify that appropriate log
/// messages are generated during the processing of requests. Mocked logging services are used to validate the expected
/// log outputs.</remarks>
public sealed class RequestPreprocessorTests
{
    /// <summary>
    /// Verifies that the mediator correctly processes commands with the expected behavior,  including logging and
    /// preprocessor functionality.
    /// </summary>
    /// <remarks>This test ensures that a command is processed successfully by the mediator,  and that the
    /// appropriate log messages are generated by both the command handler  and the preprocessor. It uses mocked logging
    /// services to validate the expected  log outputs.</remarks>
    /// <returns></returns>
    [Fact]
    public async Task PreprocessorShouldCorrectlyProcessCommands()
    {
        //---------------------------------------------------------
        // Arrange
        //---------------------------------------------------------
        // Create a service collection and add the mediator services
        var services = new ServiceCollection();
        _ = services.AddMediator(
                typeof(SimpleCommand.Handler).Assembly,
                typeof(LoggingPreProcessor<>).Assembly);
        // Set up ILogger mocks
        var loggerMock = new Mock<ILogger<SimpleCommand.Command>>();
        _ = services.AddSingleton(loggerMock.Object);
        // Build the service provider
        var serviceProvider = services.BuildServiceProvider();
        // Create an instance of the mediator
        var mediator = serviceProvider.GetRequiredService<IMediator>();
        // Create a simple command to process
        var command = new SimpleCommand.Command("Hello, World!");

        //--------------------------------------------------------
        // Act
        //---------------------------------------------------------
        // Process the command using the mediator
        var result = await mediator.SendAsync<SimpleCommand.Command, Result>(command);

        //--------------------------------------------------------
        // Assert
        //---------------------------------------------------------
        // Verify that the command was processed successfully
        Assert.NotNull(result);
        Assert.True(result.IsSuccess, "The command should have been processed successfully.");
        // Verify that the handler logger was called with the expected message
        loggerMock.Verify(
            x => x.Log(LogLevel.Debug, It.IsAny<EventId>(),
                It.Is<It.IsAnyType>((v, t) => v != null && v.ToString() == "Command received: [Hello, World!], expected to fail: [False]."),
                It.IsAny<Exception>(), (Func<It.IsAnyType, Exception?, string>)It.IsAny<object>()), Times.Once);
        loggerMock.Verify(
            x => x.Log(LogLevel.Information, It.IsAny<EventId>(),
                It.Is<It.IsAnyType>((v, t) => v != null && v.ToString() == "Command executed successfully."),
                It.IsAny<Exception>(), (Func<It.IsAnyType, Exception?, string>)It.IsAny<object>()), Times.Once);
        // Verify that the preprocessor logger was called with the expected message
        loggerMock.Verify(
            x => x.Log(LogLevel.Information, It.IsAny<EventId>(),
                It.Is<It.IsAnyType>((v, t) =>
                    v != null && v.ToString() ==
                    "Processing request of type [Boutquin.Mediator.Tests.Common.SimpleCommand+Command]."),
                It.IsAny<Exception>(), (Func<It.IsAnyType, Exception?, string>)It.IsAny<object>()), Times.Once);
    }

    /// <summary>
    /// Verifies that the preprocessor correctly processes queries and ensures the expected behavior of the mediator
    /// pipeline.
    /// </summary>
    /// <remarks>This test method validates the integration of the mediator, query handlers, and preprocessors
    /// by: - Ensuring the query is processed successfully and returns the expected result. - Verifying that the
    /// appropriate log messages are generated by the query handler and preprocessor.</remarks>
    /// <returns></returns>
    [Fact]
    public async Task PreprocessorShouldCorrectlyProcessQueries()
    {
        //---------------------------------------------------------
        // Arrange
        //---------------------------------------------------------
        // Create a service collection and add the mediator services
        var services = new ServiceCollection();
        _ = services.AddMediator(
            typeof(SimpleQuery.Handler).Assembly,
            typeof(LoggingPreProcessor<>).Assembly);
        // Set up ILogger mocks
        var loggerMock = new Mock<ILogger<SimpleQuery.Query>>();
        _ = services.AddSingleton(loggerMock.Object);
        // Build the service provider
        var serviceProvider = services.BuildServiceProvider();
        // Create an instance of the mediator
        var mediator = serviceProvider.GetRequiredService<IMediator>();
        // Create a simple query to process
        var query = new SimpleQuery.Query("Ping...");

        //--------------------------------------------------------
        // Act
        //---------------------------------------------------------
        // Process the command using the mediator
        var result = await mediator.SendAsync<SimpleQuery.Query, Result<SimpleQuery.Output>>(query);

        //--------------------------------------------------------
        // Assert
        //---------------------------------------------------------
        // Verify that the query was processed successfully
        Assert.NotNull(result);
        Assert.True(result.IsSuccess, "The query should have been processed successfully.");
        // Verify that the output is correct
        Assert.NotNull(result.Value);
        Assert.NotNull(result.Value.Reply);
        Assert.Equal("Processed message: [Ping...].", result.Value.Reply);
        // Verify that the handler logger was called with the expected message
        loggerMock.Verify(
            x => x.Log(LogLevel.Debug, It.IsAny<EventId>(),
                It.Is<It.IsAnyType>((v, t) => v != null && v.ToString() == "Query received: [Ping...], expected to fail: [False]."),
                It.IsAny<Exception>(), (Func<It.IsAnyType, Exception?, string>)It.IsAny<object>()), Times.Once);
        loggerMock.Verify(
            x => x.Log(LogLevel.Information, It.IsAny<EventId>(),
                It.Is<It.IsAnyType>((v, t) => v != null && v.ToString() == "Query executed successfully."),
                It.IsAny<Exception>(), (Func<It.IsAnyType, Exception?, string>)It.IsAny<object>()), Times.Once);
        // Verify that the preprocessor logger was called with the expected message
        loggerMock.Verify(
            x => x.Log(LogLevel.Information, It.IsAny<EventId>(),
                It.Is<It.IsAnyType>((v, t) =>
                    v != null && v.ToString() ==
                    "Processing request of type [Boutquin.Mediator.Tests.Common.SimpleQuery+Query]."),
                It.IsAny<Exception>(), (Func<It.IsAnyType, Exception?, string>)It.IsAny<object>()), Times.Once);
    }
}
